def collectors():
    return {name: import_module(f"aura.apps.{name}").collect for name in APPS}


def target_contract(target_id):
    app = target_id.split(".", 1)[0]
    try:
        return APPS[app]['targets'][target_id]
    except KeyError:
        raise ValueError(f"{target_id}: unsupported target rules") from None


